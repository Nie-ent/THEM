/**
 * Headless balance bot (P1-10). `pnpm balance [--seeds N] [--out path]`.
 * Plays N seeds in "planner" and "no-build" modes through @them/core and writes a markdown report
 * (default docs/qa/balance-latest.md). Reports numbers; never tunes content.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { CONTENT_VERSION, content } from '../../packages/content/src/index';
import type { Mode } from './policy';
import { playOne, type RunResult } from './play';

const args = process.argv.slice(2);
const argVal = (name: string) => { const i = args.indexOf(name); return i >= 0 ? args[i + 1] : undefined; };
const SEEDS = Number(argVal('--seeds') ?? 50);
const OUT = argVal('--out') ?? fileURLToPath(new URL('../../docs/qa/balance-latest.md', import.meta.url));
const MODES: Mode[] = ['planner', 'no-build'];

const pct = (xs: number[], p: number) => {
  if (xs.length === 0) return 0;
  const s = [...xs].sort((a, b) => a - b);
  return s[Math.min(s.length - 1, Math.max(0, Math.ceil((p / 100) * s.length) - 1))]!;
};
const f1 = (n: number) => n.toFixed(1);
const pc = (n: number, d: number) => (d ? `${Math.round((n / d) * 100)}%` : '–');

function summarise(rs: RunResult[]) {
  const n = rs.length;
  const wins = rs.filter((r) => r.result === 'win');
  const grades = { S: 0, A: 0, B: 0, C: 0 } as Record<string, number>;
  for (const r of rs) grades[r.score.grade]!++;
  const winGrades = { S: 0, A: 0, B: 0, C: 0 } as Record<string, number>;
  for (const r of wins) winGrades[r.score.grade]!++;
  const waves = rs.map((r) => r.wave);
  const scores = rs.map((r) => r.score.total);
  const perf = rs.map((r) => r.score.performance);
  const waveHist = new Map<number, number>();
  for (const r of rs) if (r.result !== 'win') waveHist.set(r.wave, (waveHist.get(r.wave) ?? 0) + 1);
  return {
    n, wins: wins.length,
    winAB: wins.filter((r) => r.score.grade === 'A' || r.score.grade === 'B' || r.score.grade === 'S').length,
    timeouts: rs.filter((r) => r.result === 'timeout').length,
    heroDeaths: rs.filter((r) => r.cause === 'hero').length,
    coreDeaths: rs.filter((r) => r.cause === 'core').length,
    grades, winGrades,
    wave: { mean: waves.reduce((a, b) => a + b, 0) / n, p10: pct(waves, 10), p50: pct(waves, 50), p90: pct(waves, 90) },
    score: { p10: pct(scores, 10), p50: pct(scores, 50), p90: pct(scores, 90), max: pct(scores, 100) },
    perf: { p50: pct(perf, 50) },
    simMin: rs.reduce((a, r) => a + r.simSeconds, 0) / n / 60,
    wallMs: { mean: rs.reduce((a, r) => a + r.wallMs, 0) / n, total: rs.reduce((a, r) => a + r.wallMs, 0) },
    built: rs.reduce((a, r) => a + r.structuresBuilt, 0) / n,
    lossWaves: [...waveHist].sort((a, b) => a[0] - b[0]).map(([w, c]) => `w${w}×${c}`).join(' ') || '–',
  };
}

const t0 = performance.now();
const results: Record<Mode, RunResult[]> = { planner: [], 'no-build': [] };
for (const mode of MODES) {
  for (let s = 1; s <= SEEDS; s++) {
    const { out } = playOne(content, s, mode);
    results[mode].push(out);
    process.stdout.write(`\r${mode} ${s}/${SEEDS}`);
  }
  process.stdout.write('\n');
}
const S = { planner: summarise(results.planner), 'no-build': summarise(results['no-build']) };
const total = (performance.now() - t0) / 1000;

const row = (label: string, f: (s: ReturnType<typeof summarise>) => string) => `| ${label} | ${MODES.map((m) => f(S[m])).join(' | ')} |`;
// Owner decision 31 Oct (docs/PHASE1.md): planner wins about 50% (QA band 35–65%), no-build loses
// almost always (QA bar >= 90%), and a loss is graded C at best.
const plannerRate = S.planner.wins / S.planner.n;
const dodPlanner = plannerRate >= 0.35 && plannerRate <= 0.65;
const dodNoBuild = (S['no-build'].n - S['no-build'].wins) / S['no-build'].n >= 0.9;
const lossesAboveC = MODES.flatMap((m) => results[m]).filter((r) => r.result !== 'win' && r.score.grade !== 'C').length;

const md = `# Balance bot — latest run

Generated by \`pnpm balance --seeds ${SEEDS}\` (\`tests/balance/\`). Content version \`${CONTENT_VERSION}\`,
world \`${content.worlds[0]!.id}\` (${content.worlds[0]!.waves.length} waves), normal difficulty, recommended power,
all AI heroes. Seeds 1…${SEEDS}. Total wall time ${f1(total)} s. Numbers only — QA does not tune content.

## Definition-of-done check (docs/PHASE1.md)

| Criterion | Result | Status |
| --- | --- | --- |
| Planner wins about 50% of seeds (QA band 35–65%) | ${S.planner.wins}/${S.planner.n} (${pc(S.planner.wins, S.planner.n)}) won; ${S.planner.winAB} of them S/A/B | ${dodPlanner ? 'PASS' : 'FAIL'} |
| No-build loses almost always (QA bar ≥ 90%) | ${S['no-build'].n - S['no-build'].wins}/${S['no-build'].n} (${pc(S['no-build'].n - S['no-build'].wins, S['no-build'].n)}) lost | ${dodNoBuild ? 'PASS' : 'FAIL'} |
| A loss is graded C at best | ${lossesAboveC} losses graded above C | ${lossesAboveC === 0 ? 'PASS' : 'FAIL'} |

## Summary

| Metric | planner | no-build |
| --- | --- | --- |
${row('Runs', (s) => String(s.n))}
${row('Win rate', (s) => `${s.wins}/${s.n} (${pc(s.wins, s.n)})`)}
${row('Losses: hero died / Core destroyed', (s) => `${s.heroDeaths} / ${s.coreDeaths}`)}
${row('Timeouts (60 sim-min)', (s) => String(s.timeouts))}
${row('Wave reached mean (p10 / p50 / p90)', (s) => `${f1(s.wave.mean)} (${s.wave.p10} / ${s.wave.p50} / ${s.wave.p90})`)}
${row('Wave of loss (histogram)', (s) => s.lossWaves)}
${row('Grade S / A / B / C (all runs)', (s) => `${s.grades.S} / ${s.grades.A} / ${s.grades.B} / ${s.grades.C}`)}
${row('Grade S / A / B / C (wins only)', (s) => `${s.winGrades.S} / ${s.winGrades.A} / ${s.winGrades.B} / ${s.winGrades.C}`)}
${row('Score p10 / p50 / p90 / max', (s) => `${s.score.p10} / ${s.score.p50} / ${s.score.p90} / ${s.score.max}`)}
${row('Performance (M_speed×M_damage) p50', (s) => s.perf.p50.toFixed(3))}
${row('Structures built per run (mean)', (s) => f1(s.built))}
${row('Sim time per run (min)', (s) => f1(s.simMin))}
${row('Wall time per run (ms, mean)', (s) => f1(s.wallMs.mean))}

## Per seed

| Seed | planner | no-build |
| --- | --- | --- |
${results.planner.map((p, i) => {
  const n = results['no-build'][i]!;
  const c = (r: RunResult) => `${r.result} w${r.wave}${r.cause ? ` (${r.cause})` : ''} ${r.score.grade} ${r.score.total}`;
  return `| ${p.seed} | ${c(p)} | ${c(n)} |`;
}).join('\n')}

## Bot policy (tests/balance/policy.ts)

- **Movement:** dodge active telegraphs, kite enemies within 110 px, close to ~180 px of the enemy
  nearest the Core, collect pickups inside a 260 px leash around the Core.
- **Cards:** value = rarity (+0.75 when levelling an owned card, +0.5 for damage/projectile tags,
  −1.25 when the card has a drawback); reroll offers worth < 1 while rerolls last.
- **Build (planner only):** each prep, read intel; for each threatened side (heaviest first) place
  a tower 2 cells out and a wall 4 cells out, 3 passes; fireproof walls/towers first when the wave
  has igniters; keep one wave of upkeep in reserve; post the first AI hero 120 px toward the heaviest
  side. Then call the wave early.
- **no-build:** same, but never builds or moves AI heroes.
`;

writeFileSync(OUT, md);
console.log(`planner: win ${S.planner.wins}/${S.planner.n}, A/B wins ${S.planner.winAB}; no-build: win ${S['no-build'].wins}/${S['no-build'].n}; ${f1(total)} s → ${OUT}`);
