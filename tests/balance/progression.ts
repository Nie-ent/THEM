/**
 * Balance with meta progression (P2 review). `pnpm balance:progression [--seeds N]`.
 * Plays the QA planner and no-build bots with each reference profile's run config
 * (`buildRunConfig`) and writes docs/qa/balance-progression.md.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { content } from '../../packages/content/src/index';
import { createRun, type RunConfig } from '../../packages/core/src/index';
import { buildLoadout, buildRunConfig } from '../../packages/meta/src/index';
import type { Mode } from './policy';
import { playOne, type RunResult } from './play';
import { referenceProfiles } from './profiles';

const args = process.argv.slice(2);
const SEEDS = Number(args[args.indexOf('--seeds') + 1] || 30);
const OUT = fileURLToPath(new URL('../../docs/qa/balance-progression.md', import.meta.url));
const world = content.worlds[0]!.id;

const pct = (n: number, d: number) => `${Math.round((n / d) * 100)}%`;
const med = (xs: number[]) => [...xs].sort((a, b) => a - b)[Math.floor(xs.length / 2)]!;

const rows: string[] = [];
const modsRows: string[] = [];
for (const np of referenceProfiles()) {
  const cfg: Partial<RunConfig> = np.profile ? buildRunConfig(np.profile, content, { worldId: world }) : {};
  if (np.profile) {
    const lo = buildLoadout(np.profile, content).loadout;
    const m = Object.entries(lo.mods ?? {}).filter(([, v]) => v !== 0).map(([k, v]) => `${k} ${v > 0 ? '+' : ''}${Math.round(v * 1000) / 1000}`).join(', ');
    const allies = Object.entries(lo.allyMods ?? {}).map(([h, a]) => `${h} hp+${Math.round((a.hpMult ?? 0) * 100)}% dmg+${Math.round((a.damageMult ?? 0) * 100)}%`).join('; ');
    const lim = createRun({ worldId: world, ...cfg }, content, 1).limiter;
    const pw = `${Math.round(lim.power)} → ${Math.round(lim.effectivePower)} (scale ${lim.scale.toFixed(3)}, allies ×${lim.allyFactor.toFixed(2)})`;
    modsRows.push(`| ${np.name} | ${m || '–'} | ${allies || '–'} | ${pw} |`);
  }
  for (const mode of ['planner', 'no-build'] as Mode[]) {
    const rs: RunResult[] = [];
    for (let s = 1; s <= SEEDS; s++) rs.push(playOne(content, s, mode, { config: cfg }).out);
    const wins = rs.filter((r) => r.result === 'win');
    const g = { S: 0, A: 0, B: 0, C: 0 } as Record<string, number>;
    for (const r of rs) g[r.score.grade]!++;
    rows.push(`| ${np.name} | ${mode} | ${wins.length}/${SEEDS} (${pct(wins.length, SEEDS)}) | ${med(rs.map((r) => r.wave))} | ${g.S}/${g.A}/${g.B}/${g.C} | ${med(rs.map((r) => r.score.total))} | ${(med(rs.map((r) => r.simSeconds)) / 60).toFixed(1)} |`);
    process.stdout.write(`${np.name} ${mode}: ${wins.length}/${SEEDS}\n`);
  }
}

const md = `# Balance with progression

Generated by \`pnpm balance:progression --seeds ${SEEDS}\` (\`tests/balance/progression.ts\`, profiles in
\`tests/balance/profiles.ts\`). World \`${world}\`, normal difficulty, same QA bot policy and seeds 1…${SEEDS}
as \`balance-latest.md\`. Each run uses \`buildRunConfig(profile)\`; core derives power from the loadout
and the difficulty limiter scales it above the world's recommended power (packages/core/src/power.ts).

## Results

| Profile | Mode | Wins | Median wave | Grades S/A/B/C | Median score | Median sim min |
| --- | --- | --- | --- | --- | --- | --- |
${rows.join('\n')}

## Loadout per profile

| Profile | Run mods (sum) | AI hero growth | Power → after limiter (recommended 100) |
| --- | --- | --- | --- |
${modsRows.join('\n')}

## Profiles

${referenceProfiles().map((p) => `- **${p.name}**: ${p.desc}`).join('\n')}
`;
writeFileSync(OUT, md);
console.log(`→ ${OUT}`);
